const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('industry-sentiment.js', 'utf8');
const nodes = new Map();
const el = id => { if (!nodes.has(id)) nodes.set(id, {textContent:'',innerHTML:''}); return nodes.get(id); };
const sandbox = {el, numeric:Number, esc:String, signed:(v,d)=>`${v>=0?'+':''}${v.toFixed(d)}`, signClass:v=>v>=0?'positive':'negative'};
vm.createContext(sandbox);
vm.runInContext(source.slice(source.indexOf('function fundOwBar('), source.indexOf('function renderFundOverweight()')), sandbox);
const rows = Array.from({length:31}, (_,i)=>({code:String(i),name:`行业${i}`,previousOverPp:0,currentOverPp:0,changeOverPp:0,weightChangePp:0,benchmarkChangePp:0}));
Object.assign(rows[0], {name:'基准驱动上升',previousOverPp:-2,currentOverPp:-1,changeOverPp:1,benchmarkChangePp:-1});
Object.assign(rows[1], {name:'下降第一',previousOverPp:1,currentOverPp:-1,changeOverPp:-2,weightChangePp:-2});
Object.assign(rows[2], {name:'上升第一',previousOverPp:0,currentOverPp:2,changeOverPp:2,weightChangePp:2});
Object.assign(rows[3], {name:'下降第二',previousOverPp:0,currentOverPp:-1,changeOverPp:-1,weightChangePp:-1});
const payload = {asOf:'2026-10-16',comparison:{asOf:'2026-10-16',previousAsOf:'2026-10-08',industries:rows}};
sandbox.renderFundChanges(payload);
assert.equal(el('fundChangeDates').textContent,'2026-10-08 → 2026-10-16');
assert.ok(el('fundChangeUp').innerHTML.indexOf('上升第一') < el('fundChangeUp').innerHTML.indexOf('基准驱动上升'));
assert.ok(el('fundChangeDown').innerHTML.indexOf('下降第一') < el('fundChangeDown').innerHTML.indexOf('下降第二'));
assert.ok(el('fundChangeUp').innerHTML.includes('基金配置 +0.00pp · 市场基准 -1.00pp'));
assert.ok(!el('fundChangeUp').innerHTML.includes('行业4'));
assert.equal(el('fundChangeUpNote').textContent,'2个行业上升');
Object.assign(rows[0], {previousOverPp:-0.004,currentOverPp:0,changeOverPp:0.004,benchmarkChangePp:-0.004});
sandbox.renderFundChanges(payload);
assert.ok(el('fundChangeUp').innerHTML.includes('+0.0040pp'));
rows[0].changeOverPp=null;
sandbox.renderFundChanges(payload);
assert.ok(el('fundChangeDates').textContent.includes('暂无完整'));
assert.ok(!el('fundChangeUp').innerHTML.includes('上升第一'));
sandbox.renderFundChanges(null);
assert.ok(el('fundChangeDown').innerHTML.includes('暂无可比较'));
console.log('PASS: weekly change signs, sorting, benchmark decomposition and missing-data handling');
